// Command gen writes the error catalog from spec/errors.json: codes_gen.go, the engine and app
// copies, and docs/errors.md. Run it with go generate ./internal/errs, which runs it in
// internal/errs, so the paths below are relative to that directory.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strings"
)

type entry struct {
	Code    string   `json:"code"`
	Title   string   `json:"title"`
	Problem string   `json:"problem"`
	Cause   string   `json:"cause"`
	Fix     string   `json:"fix"`
	Where   []string `json:"where"`
}

const (
	specFile = "../../spec/errors.json"
	goFile   = "codes_gen.go"
	jsFile   = "../../app/engine/lib/errors.gen.js"
	dartFile = "../../app/lib/src/errors.g.dart"
	docsFile = "../../docs/errors.md"
	banner   = "Code generated by internal/errs/gen from spec/errors.json. DO NOT EDIT."
)

var dartEscaper = strings.NewReplacer(`\`, `\\`, `'`, `\'`, `$`, `\$`, "\n", `\n`, "\r", `\r`)

// dartQuote returns s as a single-quoted Dart string literal.
func dartQuote(s string) string {
	return "'" + dartEscaper.Replace(s) + "'"
}

func main() {
	if err := run(); err != nil {
		log.Fatal(err)
	}
}

func run() error {
	data, err := os.ReadFile(specFile)
	if err != nil {
		return err
	}
	var spec struct {
		Codes []entry `json:"codes"`
	}
	if err := json.Unmarshal(data, &spec); err != nil {
		return err
	}
	goSrc, err := goCode(spec.Codes)
	if err != nil {
		return err
	}
	jsSrc, err := jsCode(spec.Codes)
	if err != nil {
		return err
	}
	outputs := map[string][]byte{
		goFile:   goSrc,
		jsFile:   jsSrc,
		dartFile: dartCode(spec.Codes),
		docsFile: docsPage(spec.Codes),
	}
	for path, src := range outputs {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, src, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func goCode(codes []entry) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\npackage errs\n\n// Catalog maps each code to its entry.\nvar Catalog = map[string]Entry{\n", banner)
	for _, c := range codes {
		where := make([]string, len(c.Where))
		for i, w := range c.Where {
			where[i] = fmt.Sprintf("%q", w)
		}
		fmt.Fprintf(&b, "\t%q: {Code: %q, Title: %q, Problem: %q, Cause: %q, Fix: %q, Where: []string{%s}},\n",
			c.Code, c.Code, c.Title, c.Problem, c.Cause, c.Fix, strings.Join(where, ", "))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func jsCode(codes []entry) ([]byte, error) {
	byCode := make(map[string]entry, len(codes))
	for _, c := range codes {
		byCode[c.Code] = c
	}
	js, err := json.MarshalIndent(byCode, "", "  ")
	if err != nil {
		return nil, err
	}
	return []byte(fmt.Sprintf("// %s\nmodule.exports = { CODES: %s };\n", banner, js)), nil
}

func dartCode(codes []entry) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\n", banner)
	b.WriteString(`class HbErrorEntry {
  const HbErrorEntry({
    required this.code,
    required this.title,
    required this.problem,
    required this.cause,
    required this.fix,
    required this.where,
  });

  final String code;
  final String title;
  final String problem;
  final String cause;
  final String fix;
  final List<String> where;
}

const Map<String, HbErrorEntry> errorCatalog = {
`)
	for _, c := range codes {
		where := make([]string, len(c.Where))
		for i, w := range c.Where {
			where[i] = dartQuote(w)
		}
		fmt.Fprintf(&b, "  %s: HbErrorEntry(code: %s, title: %s, problem: %s, cause: %s, fix: %s, where: [%s]),\n",
			dartQuote(c.Code), dartQuote(c.Code), dartQuote(c.Title), dartQuote(c.Problem),
			dartQuote(c.Cause), dartQuote(c.Fix), strings.Join(where, ", "))
	}
	b.WriteString("};\n")
	return b.Bytes()
}

// docsPage writes one section per code. Empty fields are left out, so a code with no wording yet
// has its heading and nothing else.
func docsPage(codes []entry) []byte {
	var b bytes.Buffer
	b.WriteString("# Error codes\n\nGenerated from spec/errors.json by go generate ./internal/errs. Do not edit by hand.\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "\n## %s\n", c.Code)
		for _, p := range []struct{ label, text string }{{"Problem", c.Problem}, {"Cause", c.Cause}, {"Fix", c.Fix}} {
			if p.text != "" {
				fmt.Fprintf(&b, "\n**%s:** %s\n", p.label, p.text)
			}
		}
	}
	return b.Bytes()
}
